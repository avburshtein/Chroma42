/**
 * Якоря статусов (STATUS_SEED_ANCHORS).
 *
 * Канонические сиды четырёх семантических статусов. Якоря — константы
 * движка: они не зависят от primary-сида и не подбираются гармониями,
 * потому что статусы обязаны оставаться узнаваемыми (зелёный — успех,
 * жёлтый — предупреждение, красный — ошибка, бирюзовый — информация)
 * в любой теме.
 *
 * До Этапа 12 эти значения дублировались литералами в тестах; теперь
 * единственный источник истины — этот файл.
 *
 * @see Docs/roadmap/Роадмап с учётом всех запланированных фич.md — Этап 12.1
 */

import { STATUS_NAMES } from '../policy/registry';

/** Имена статусов, для которых существуют якоря. */
export type StatusSeedName = (typeof STATUS_NAMES)[number];

/** Якоря статусов: имя статуса -> HEX-сид. */
export type StatusSeedAnchors = Record<StatusSeedName, string>;

/**
 * Якоря статусов.
 *
 * Значения намеренно тёмные и умеренно насыщенные: они используются
 * как сиды для `generateStatusScale`, который ограничивает хроматичность
 * на 0.16, поэтому якоря обязаны быть читаемыми и на светлой, и на
 * тёмной поверхности.
 *
 * @example
 * generateStatusScale(STATUS_SEED_ANCHORS.success)[50];
 */
export const STATUS_SEED_ANCHORS: StatusSeedAnchors = {
    success: '#1b5e20',
    warning: '#8a5100',
    error: '#b12a33',
    info: '#00543b',
};
